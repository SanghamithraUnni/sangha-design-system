import React from 'react';
import {beforeEach,it,expect} from 'vitest';
import {render,screen,within,fireEvent} from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import {TopicRooms} from '../../products/team-messaging/topic-rooms/TopicRooms.jsx';
import {STORAGE_KEY} from '../../products/team-messaging/topic-rooms/data.js';
beforeEach(()=>localStorage.clear());
it('requires a subject and opening message, creates a topic, and persists its reply',async()=>{
 const user=userEvent.setup();render(<TopicRooms/>);
 await user.click(screen.getByRole('button',{name:'Start a topic'}));
 const dialog=screen.getByRole('dialog',{name:'Start a topic'});
 expect(within(dialog).getByRole('button',{name:'Create topic'})).toBeDisabled();
 await user.type(within(dialog).getByLabelText(/Subject/),'Review the mobile welcome');
 await user.type(within(dialog).getByLabelText(/Opening message/),'Could we review the narrow layout?');
 await user.click(within(dialog).getByRole('button',{name:'Create topic'}));
 expect(within(screen.getByRole('region',{name:'Review the mobile welcome'})).getByRole('heading',{level:2,name:'Review the mobile welcome'})).toBeInTheDocument();
 await user.type(screen.getByLabelText('Reply in Review the mobile welcome'),'The back action is clear.{Enter}Looks good.');
 await user.click(screen.getByRole('button',{name:'Send'}));
 expect(screen.getByRole('log')).toHaveTextContent('The back action is clear. Looks good.');
 const saved=JSON.parse(localStorage.getItem(STORAGE_KEY));
 expect(saved.topics[0].messages).toHaveLength(2);
 expect(screen.getByLabelText('Reply in Review the mobile welcome')).toHaveValue('');
});
it('keeps topic and direct-message drafts separate and restores a draft on reload',async()=>{
 const user=userEvent.setup();const page=render(<TopicRooms/>);
 await user.type(screen.getByLabelText('Reply in A warmer welcome on the homepage'),'Homepage draft');
 await user.click(screen.getByRole('button',{name:'Maya Chen'}));
 expect(screen.getByLabelText('Reply to Maya Chen')).toHaveValue('');
 await user.type(screen.getByLabelText('Reply to Maya Chen'),'Private draft');
 await user.click(screen.getByRole('button',{name:/Feedback.*A warmer welcome/}));
 expect(screen.getByLabelText('Reply in A warmer welcome on the homepage')).toHaveValue('Homepage draft');
 page.unmount();render(<TopicRooms/>);
 expect(screen.getByLabelText('Reply in A warmer welcome on the homepage')).toHaveValue('Homepage draft');
 await user.click(screen.getByRole('button',{name:'Maya Chen'}));
 await user.click(screen.getByRole('button',{name:'Send'}));
 expect(screen.getByRole('log')).toHaveTextContent('Private draft');
});
it('filters unread topics, marks one read when opened, and follows and resolves topics',async()=>{
 const user=userEvent.setup();render(<TopicRooms/>);
 await user.click(screen.getByRole('button',{name:'Unread (3)'}));
 expect(screen.queryByRole('button',{name:/A small update to our icon sizing/})).not.toBeInTheDocument();
 await user.click(screen.getByRole('button',{name:/Onboarding: the first five minutes/}));
 expect(screen.getByRole('button',{name:'Unread (2)'})).toBeInTheDocument();
 await user.click(screen.getByRole('button',{name:'Unfollow topic'}));
 expect(screen.getByRole('button',{name:'Follow topic'})).toHaveAttribute('aria-pressed','false');
 await user.click(screen.getByRole('button',{name:'Mark topic resolved'}));
 expect(screen.getByRole('button',{name:'Reopen topic'})).toBeInTheDocument();
 await user.click(screen.getByRole('button',{name:'Reopen topic'}));
 expect(screen.getByRole('button',{name:'Mark topic resolved'})).toBeInTheDocument();
});
it('searches message content and supports a group reply using Ctrl+Enter',async()=>{
 const user=userEvent.setup();render(<TopicRooms/>);
 await user.type(screen.getByLabelText('Search channels and topics'),'usability');
 expect(screen.getByRole('button',{name:/Onboarding: the first five minutes/})).toBeInTheDocument();
 expect(screen.queryByRole('button',{name:/Feedback.*A warmer welcome/})).not.toBeInTheDocument();
 await user.click(screen.getByRole('button',{name:'Website working group'}));
 const input=screen.getByLabelText('Reply to Website working group');
 await user.type(input,'Ready for the review.');fireEvent.keyDown(input,{key:'Enter',ctrlKey:true});
 expect(screen.getByRole('log')).toHaveTextContent('Ready for the review.');
 expect(input).toHaveValue('');
});
